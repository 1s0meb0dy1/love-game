// Версия приложения (видна в подвале). Формат: <старшая>.<средняя>.<номер><буква>, например 0.1.29а.
// Каждое изменение приложения поднимает букву на один шаг (а → б → в … я → аа → аб …) — это делает `npm run bump` (и хук .githooks/pre-commit).
// Числа «0», «1» и «29» меняются вручную — только когда владелец об этом попросит.
export const APP_VERSION = '0.1.29б';

// Буква версии в английском интерфейсе пишется латиницей (в английском тексте кириллицы быть не должно): а → a, б → b, в → v …
const LAT = { а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ж: 'zh', з: 'z', и: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sc', э: 'ye', ю: 'yu', я: 'ya' };
export const appVersionLabel = (v, lang) => (lang === 'en' ? String(v).replace(/[а-я]/g, (ch) => LAT[ch] || ch) : String(v));
