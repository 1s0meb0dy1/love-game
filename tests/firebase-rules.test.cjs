const { initializeTestEnvironment, assertFails, assertSucceeds } = require('@firebase/rules-unit-testing');
const { ref, set, update, get, remove } = require('firebase/database');
const fs = require('node:fs'); const path = require('node:path');
(async () => {
  const rules = fs.readFileSync(path.join(__dirname, '../firebase/database.rules.template.json'), 'utf8').replaceAll('OWNER_UID', 'owner');
  const env = await initializeTestEnvironment({ projectId: 'demo-love-game', database: { host: '127.0.0.1', port: 9000, rules } });
  try {
    const a = env.authenticatedContext('alice').database(), b = env.authenticatedContext('bob').database();
    const owner = env.authenticatedContext('owner').database(), guest = env.unauthenticatedContext().database();
    const q = { id: 'q1', categoryId: 'family', level: 'Простые', text: 'Test question', targetId: '' };
    await assertSucceeds(set(ref(owner, 'questions/q1'), q));
    await assertSucceeds(get(ref(guest, 'questions')));
    await assertFails(set(ref(a, 'questions/q1'), q));
    await assertFails(set(ref(owner, 'questions/q2'), { ...q, targetId: 'ABCD2345' }));
    console.log('PASS public question reads and owner-only writes; plaintext invitation IDs rejected');
    const session = { payload: 'encrypted', updatedAt: 10 };
    await assertFails(set(ref(guest, 'sessions/s_test'), session));
    await assertSucceeds(set(ref(a, 'sessions/s_test'), session));
    await assertSucceeds(get(ref(b, 'sessions/s_test')));
    await assertFails(get(ref(a, 'sessions')));
    await assertFails(update(ref(a, 'sessions/s_test'), { updatedAt: 'bad' }));
    await assertFails(update(ref(a, 'sessions/s_test'), { extra: 'bad' }));
    await assertSucceeds(set(ref(a, 'sessions/s_test'), { payload: '', updatedAt: 11, deleted: true }));
    await assertFails(set(ref(b, 'sessions/s_test'), session));
    await assertFails(remove(ref(b, 'sessions/s_test')));
    console.log('PASS shared-session reads preserved; schema bypasses and resurrection after deletion denied');
    const live = { ver: 1, by: 'device', t: 10, status: 'active', d: 'q1,q2' };
    await assertSucceeds(set(ref(a, 'live/l_test'), live));
    await assertFails(update(ref(a, 'live/l_test'), { d: 'x'.repeat(200001) }));
    await assertFails(update(ref(a, 'live/l_test'), { pun: { id: 1, reason: 'skip', text: { html: 'bad' } } }));
    await assertSucceeds(set(ref(a, 'live/l_test'), { ver: 2, by: 'device', t: 11, status: 'ended', deleted: true }));
    await assertFails(set(ref(b, 'live/l_test'), live));
    await assertFails(update(ref(b, 'live/l_test'), { spin: { id: 1, idx: 0, winner: 'p', cands: [{ id: 'p', name: 'PII', gender: 'guy' }] } }));
    console.log('PASS live payload bounds, punishment types and permanent deletion marker enforced');
    const sessionRef = 's_' + 'a'.repeat(64);
    await assertSucceeds(set(ref(a, 'sessions/' + sessionRef), session));
    const record = { ownerUid: 'alice', sessionRef, updatedAt: 10, sid: '', names: ['A', 'B'] };
    await assertSucceeds(set(ref(a, 'analytics/full/a1'), record));
    await assertFails(get(ref(a, 'analytics/full/a1')));
    await assertSucceeds(get(ref(owner, 'analytics/full')));
    await assertFails(update(ref(b, 'analytics/full/a1'), { updatedAt: 12 }));
    await assertFails(update(ref(a, 'analytics/full/a1'), { ownerUid: 'bob' }));
    await assertFails(remove(ref(b, 'analytics/full/a1')));
    await assertSucceeds(set(ref(a, 'analytics/full/a1'), { ownerUid: 'alice', sessionRef, updatedAt: 11, deleted: true, sid: '', names: '' }));
    await assertFails(set(ref(a, 'analytics/full/a1'), record));
    await assertFails(update(ref(a, 'analytics/full/a1'), { names: ['A'], games: { g: {} } }));
    await assertFails(remove(ref(a, 'analytics/full/a1')));
    await assertSucceeds(set(ref(a, 'sessions/' + sessionRef), { payload: '', updatedAt: 12, deleted: true }));
    await assertFails(set(ref(a, 'analytics/full/new_aid_from_another_tab'), record));
    console.log('PASS analytics ownership is immutable; old tabs cannot re-upload deleted names or remove markers');
  } finally { await env.cleanup(); }
})().catch(error => { console.error('FAIL', error); process.exitCode = 1; });
